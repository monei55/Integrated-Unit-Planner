// ============================================================
// YEAR / BAND NORMALISATION
// ============================================================

export function vocabularyLevelFor(
  subject,
  yearLevel
) {

  const year =
    normaliseYearNumber(
      yearLevel
    );


  if (
    subject ===
      "English" ||
    subject ===
      "HASS" ||
    subject ===
      "Mathematics" ||
    subject ===
      "Science"
  ) {

    if (
      year ===
      0
    ) {

      return "Prep";

    }


    return `Year ${year}`;

  }


  if (
    subject ===
      "HPE" ||
    subject ===
      "Design and Technologies" ||
    subject ===
      "Digital Technologies" ||
    subject ===
      "Dance" ||
    subject ===
      "Drama" ||
    subject ===
      "Media Arts" ||
    subject ===
      "Music" ||
    subject ===
      "Visual Arts"
  ) {

    if (
      year <=
      2
    ) {

      return "Prep – Year 2";

    }


    if (
      year <=
      4
    ) {

      return "Year 3 – Year 4";

    }


    return "Year 5 – Year 6";

  }


  return yearLevel;

}


// ============================================================
// NORMALISE YEAR NUMBER
// ============================================================

export function normaliseYearNumber(
  yearLevel
) {

  const text =
    String(
      yearLevel ||
      ""
    )
      .trim();


  if (
    /prep|foundation/i.test(
      text
    )
  ) {

    return 0;

  }


  const match =
    text.match(
      /\d+/
    );


  if (!match) {

    return 0;

  }


  return Number(
    match[0]
  );

}


// ============================================================
// GET ALL VOCABULARY FOR A SUBJECT / YEAR
// ============================================================

export function getVocabularyForLevel(
  subject,
  yearLevel
) {

  const subjectData =
    VOCABULARY_DATA[
      subject
    ];


  if (!subjectData) {

    return {};

  }


  const level =
    vocabularyLevelFor(
      subject,
      yearLevel
    );


  return (
    subjectData[
      level
    ] ||
    {}
  );

}


// ============================================================
// GET VOCABULARY FOR A PARTICULAR CURRICULUM AREA
// ============================================================

export function getVocabularyForArea(
  subject,
  yearLevel,
  area
) {

  const levelData =
    getVocabularyForLevel(
      subject,
      yearLevel
    );


  if (
    !levelData ||
    !Object.keys(
      levelData
    ).length
  ) {

    return {
      tier2: [],
      tier3: []
    };

  }


  const exact =
    levelData[
      area
    ];


  if (exact) {

    return normaliseVocabularyEntry(
      exact
    );

  }


  const mappedArea =
    mapPlannerAreaToVocabularyArea(
      subject,
      area,
      levelData
    );


  if (
    mappedArea &&
    levelData[
      mappedArea
    ]
  ) {

    return normaliseVocabularyEntry(
      levelData[
        mappedArea
      ]
    );

  }


  return {
    tier2: [],
    tier3: []
  };

}


// ============================================================
// PLANNER AREA → VOCABULARY AREA
//
// The current planner uses some teacher-friendly area labels
// that differ slightly from the vocabulary scope headings.
// ============================================================

export function mapPlannerAreaToVocabularyArea(
  subject,
  area,
  levelData = {}
) {

  const text =
    String(
      area ||
      ""
    )
      .toLowerCase();


  // ----------------------------------------------------------
  // English
  // ----------------------------------------------------------

  if (
    subject ===
    "English"
  ) {

    if (
      /literature|literary|character|setting|plot/.test(
        text
      )
    ) {

      return "Literature";

    }


    if (
      /reading|viewing|writing|creating|speaking|listening|literacy/.test(
        text
      )
    ) {

      return "Literacy";

    }


    return "Language";

  }


  // ----------------------------------------------------------
  // HASS
  // ----------------------------------------------------------

  if (
    subject ===
    "HASS"
  ) {

    if (
      /history/.test(
        text
      )
    ) {

      return "History";

    }


    if (
      /geograph/.test(
        text
      )
    ) {

      return "Geography";

    }


    if (
      /civic|citizen/.test(
        text
      )
    ) {

      return "Civics & Citizenship";

    }


    if (
      /economic|business/.test(
        text
      )
    ) {

      return "Economics & Business";

    }


    if (
      /skill|inquiry/.test(
        text
      )
    ) {

      return "HASS Skills";

    }

  }


  // ----------------------------------------------------------
  // Mathematics
  // ----------------------------------------------------------

  if (
    subject ===
    "Mathematics"
  ) {

    const mathematicsAreas = [
      "Number",
      "Algebra",
      "Measurement",
      "Space",
      "Statistics",
      "Probability"
    ];


    const found =
      mathematicsAreas.find(
        (candidate) =>
          text.includes(
            candidate.toLowerCase()
          )
      );


    if (found) {

      return found;

    }

  }


  // ----------------------------------------------------------
  // Science
  // ----------------------------------------------------------

  if (
    subject ===
    "Science"
  ) {

    if (
      /life|living|biolog/.test(
        text
      )
    ) {

      return "Biological Sciences";

    }


    if (
      /material|chemical/.test(
        text
      )
    ) {

      return "Chemical Sciences";

    }


    if (
      /physical|force|energy|light|heat/.test(
        text
      )
    ) {

      return "Physical Sciences";

    }


    if (
      /earth|space/.test(
        text
      )
    ) {

      return "Earth & Space Sciences";

    }


    if (
      /inquiry|investigat|skill/.test(
        text
      )
    ) {

      return "Science Inquiry";

    }

  }


  // ----------------------------------------------------------
  // HPE
  // ----------------------------------------------------------

  if (
    subject ===
    "HPE"
  ) {

    if (
      /movement|physical|sport|fitness|motor|game/.test(
        text
      )
    ) {

      return "Movement & Physical Activity";

    }


    if (
      /relationship|safety|safe|protect|consent/.test(
        text
      )
    ) {

      return "Relationships & Safety";

    }


    if (
      /skill|decision|information|message|reflect/.test(
        text
      )
    ) {

      return "Health & Wellbeing Skills";

    }


    return "Personal, Social & Community Health";

  }


  // ----------------------------------------------------------
  // Design Technologies
  // ----------------------------------------------------------

  if (
    subject ===
    "Design and Technologies"
  ) {

    if (
      /process|production|skill|create|produce|evaluate/.test(
        text
      )
    ) {

      return "Processes & Production Skills";

    }


    return "Design & Technologies";

  }


  // ----------------------------------------------------------
  // Digital Technologies
  // ----------------------------------------------------------

  if (
    subject ===
    "Digital Technologies"
  ) {

    if (
      /algorithm|privacy|security|safe|skill|process|data/.test(
        text
      )
    ) {

      return "Digital Skills & Safety";

    }


    return "Digital Technologies";

  }


  // ----------------------------------------------------------
  // Arts
  // ----------------------------------------------------------

  if (
    [
      "Dance",
      "Drama",
      "Media Arts",
      "Music",
      "Visual Arts"
    ]
      .includes(
        subject
      )
  ) {

    if (
      levelData[
        subject
      ]
    ) {

      return subject;

    }


    if (
      levelData[
        "Arts Practices"
      ]
    ) {

      return "Arts Practices";

    }

  }


  return null;

}


// ============================================================
// GET COMBINED VOCABULARY FOR MULTIPLE AREAS
// ============================================================

export function combineVocabulary(
  entries
) {

  const tier2 = [];

  const tier3 = [];


  (
    entries ||
    []
  )
    .forEach(
      (entry) => {

        (
          entry?.tier2 ||
          []
        )
          .forEach(
            (word) =>
              tier2.push(
                word
              )
          );


        (
          entry?.tier3 ||
          []
        )
          .forEach(
            (word) =>
              tier3.push(
                word
              )
          );

      }
    );


  return {

    tier2:
      uniqueWords(
        tier2
      ),

    tier3:
      uniqueWords(
        tier3
      )

  };

}


// ============================================================
// NORMALISE ENTRY
// ============================================================

function normaliseVocabularyEntry(
  entry
) {

  return {

    tier2:
      uniqueWords(
        entry?.tier2 ||
        []
      ),

    tier3:
      uniqueWords(
        entry?.tier3 ||
        []
      )

  };

}


// ============================================================
// UNIQUE WORDS
// ============================================================

export function uniqueWords(
  values
) {

  const seen =
    new Set();


  const result = [];


  (
    values ||
    []
  )
    .forEach(
      (value) => {

        const word =
          String(
            value ||
            ""
          )
            .trim();


        if (!word) {
          return;
        }


        const key =
          word
            .toLowerCase();


        if (
          seen.has(
            key
          )
        ) {

          return;

        }


        seen.add(
          key
        );


        result.push(
          word
        );

      }
    );


  return result;

}